"""
退款流水的关联 ID

数据库对「同一用户 + 同一退款类型 + 同一 reference_id」有唯一约束（防重复退款），
因此 reference_id 必须能唯一对应**一笔扣费**：

- 可能被重试 / 重投递的退款（Celery 任务失败）：用任务或记录的稳定 ID，
  重复执行时会被约束挡住——这正是约束要防的场景；
- 请求内的一次性退款（入队失败、同步生成失败）：不会重试，但同一文档可能被扣费多次，
  用文档 ID 会让第二笔合法退款撞上约束，故附加随机后缀。
"""
from uuid import uuid4


def one_off_refund_reference(scope) -> str:
    """请求内一次性退款的关联 ID：保留文档 ID 便于对账，附随机后缀保证每笔唯一"""
    return f"{scope}:{uuid4().hex[:12]}"
