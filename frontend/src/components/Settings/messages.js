const lookup = (table, key) => key.split('.').reduce((node, part) => (node == null ? node : node[part]), table)

export function translate(locale, key, vars) {
  let text = lookup(MESSAGES[locale], key)
  if (typeof text !== 'string') text = lookup(MESSAGES.zh, key)
  if (typeof text !== 'string') return key
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (match, name) => (vars[name] ?? match))
}

/** 设置页取文案：const { t, locale } = useSettingsT() */
export function useSettingsT() {
  const locale = useLocaleStore((s) => s.locale)
  const t = useCallback((key, vars) => translate(locale, key, vars), [locale])
  return { t, locale }
}

/**
 * 把接口错误翻译成当前语言。
 * 后端设置接口带稳定 code；Base URL 格式错误来自参数校验（422），按字段识别。
 * 没有对应译文时：中文界面显示后端原文，英文界面显示通用文案。
 */
export function describeError(t, locale, err, fallbackKey) {
  if (!err) return t(fallbackKey)
  let code = err.code
  if (code === 'VALIDATION_ERROR' && Array.isArray(err.details)
    && err.details.some((item) => Array.isArray(item?.loc) && item.loc.includes('base_url'))) {
    code = 'INVALID_BASE_URL'
  }
  if (code && typeof lookup(MESSAGES.en.errors, code) === 'string') return t(`errors.${code}`)
  if (locale === 'zh' && err.message) return err.message
  return t(fallbackKey)
}
